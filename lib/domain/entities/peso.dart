class Peso {
  final String id;
  final double peso;
  final DateTime fecha;
  final double imc;
  final double pesoPerdido;
  final double proyeccion;
  final String perfilId;

  Peso({
    required this.id,
    required this.peso,
    required this.fecha,
    required this.imc,
    required this.pesoPerdido,
    required this.proyeccion,
    required this.perfilId,
  });
}
